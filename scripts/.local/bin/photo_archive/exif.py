"""exiftool plumbing shared by the photo-archive tools.

Every tool talks to exiftool through an ExifTool instance, which owns that
tool's private XMP namespace and the generated .ExifTool_config declaring it.
Keeping the declaration out of ~/.ExifTool_config means it only ever applies to
this package's calls.
"""

from __future__ import annotations

import concurrent.futures
import json
import os
import subprocess
import tempfile
from dataclasses import dataclass, field
from pathlib import Path
from typing import Sequence

from photo_archive.util import LOG


@dataclass(frozen=True)
class Namespace:
    """A private XMP namespace and the string tags it declares.

    group2 is exiftool's family-2 group, which decides where the tags show up
    in grouped output: 'Image' for bookkeeping, 'Location' for anything
    geographic.
    """

    prefix: str
    uri: str
    tags: tuple[str, ...]
    group2: str = "Image"

    def qualify(self, tag: str) -> str:
        """Fully qualified tag name, e.g. 'XMP-vidgeo:GeoSpread'."""
        return f"XMP-{self.prefix}:{tag}"


def config_body(namespace: Namespace, generator: str) -> str:
    """Render the .ExifTool_config declaring one private namespace."""
    declarations = "\n".join(
        f"    {tag:<14}=> {{ }}," for tag in namespace.tags
    )
    return f"""\
# Generated by {generator}. Safe to delete; it will be recreated.
#
# Declares a private XMP namespace used for this tool's own bookkeeping. Kept
# out of ~/.ExifTool_config on purpose so it only applies to this tool's
# exiftool calls.
%Image::ExifTool::UserDefined = (
    'Image::ExifTool::XMP::Main' => {{
        {namespace.prefix} => {{
            SubDirectory => {{
                TagTable => 'Image::ExifTool::UserDefined::{namespace.prefix}',
            }},
        }},
    }},
);

%Image::ExifTool::UserDefined::{namespace.prefix} = (
    GROUPS    => {{ 0 => 'XMP', 1 => 'XMP-{namespace.prefix}', 2 => '{namespace.group2}' }},
    NAMESPACE => {{ '{namespace.prefix}' => '{namespace.uri}' }},
    WRITABLE  => 'string',
{declarations}
);

1;  #end
"""


@dataclass
class ExifTool:
    """Bound exiftool runner for one tool's config and namespace."""

    config_path: Path
    namespace: Namespace
    generator: str
    _ensured: bool = field(default=False, init=False, repr=False)

    def ensure_config(self) -> Path:
        """Write the private-namespace config if it is missing or stale."""
        body = config_body(self.namespace, self.generator)
        self.config_path.parent.mkdir(parents=True, exist_ok=True)
        current = None
        if self.config_path.exists():
            current = self.config_path.read_text(encoding="utf-8")
        if current != body:
            self.config_path.write_text(body, encoding="utf-8")
            LOG.debug("wrote exiftool config: %s", self.config_path)
        self._ensured = True
        return self.config_path

    def argv(self, *args: str) -> list[str]:
        """Build an exiftool command line.

        '-config' is only honoured when it is the very first option, so it is
        always prepended here rather than passed by callers.
        """
        return [
            "exiftool",
            "-config",
            str(self.config_path),
            "-charset",
            "utf8",
            "-charset",
            "filename=utf8",
            *args,
        ]

    def run(
        self, args: Sequence[str], check: bool = False
    ) -> subprocess.CompletedProcess:
        proc = subprocess.run(
            self.argv(*args),
            capture_output=True,
            text=True,
            encoding="utf-8",
            errors="replace",
        )
        if check and proc.returncode != 0:
            raise RuntimeError(
                f"exiftool failed ({proc.returncode}): {proc.stderr.strip()}"
            )
        return proc

    def read(
        self,
        paths: Sequence[Path],
        tags: Sequence[str],
        numeric: bool = False,
        jobs: int = 1,
    ) -> dict[Path, dict]:
        """Read tags from many files, batched into as few invocations as possible.

        Paths go through an argfile so each call is immune to ARGV length
        limits; 24k sidecars in one shot is normal.

        numeric passes -n, which is required for GPS: without it coordinates
        come back as human-readable strings rather than signed decimals.

        exiftool is single-threaded Perl and reading tens of thousands of
        sidecars is CPU-bound in it, so jobs > 1 splits the list across that
        many processes. Results are keyed by path and merged, so the split is
        invisible to callers.
        """
        if not paths:
            return {}
        if jobs > 1 and len(paths) > jobs * 64:
            size = -(-len(paths) // jobs)
            chunks = [paths[i:i + size] for i in range(0, len(paths), size)]
            merged: dict[Path, dict] = {}
            with concurrent.futures.ThreadPoolExecutor(max_workers=jobs) as pool:
                for part in pool.map(
                    lambda chunk: self.read(chunk, tags, numeric), chunks
                ):
                    merged.update(part)
            return merged

        tag_args = [f"-{tag}" for tag in tags]
        with tempfile.NamedTemporaryFile(
            "w", suffix=".args", delete=False, encoding="utf-8"
        ) as handle:
            for path in paths:
                handle.write(f"{path}\n")
            argfile = handle.name
        try:
            args = ["-j", "-G1", "-m"]
            if numeric:
                args.append("-n")
            proc = self.run([*args, *tag_args, "-@", argfile])
            if not proc.stdout.strip():
                if proc.returncode != 0:
                    LOG.debug(
                        "exiftool read returned nothing: %s", proc.stderr.strip()
                    )
                return {}
            try:
                records = json.loads(proc.stdout)
            except json.JSONDecodeError as exc:
                LOG.error("could not parse exiftool output: %s", exc)
                return {}
            return {Path(rec["SourceFile"]): rec for rec in records}
        finally:
            os.unlink(argfile)

    def write(
        self,
        target: Path,
        assignments: Sequence[str],
        dry_run: bool,
        numeric: bool = False,
        preserve_mtime: bool = True,
    ) -> bool:
        """Apply tag assignments to one sidecar.

        exiftool's own -P keeps whole seconds but truncates the sub-second part
        of the timestamp, so the original atime/mtime are captured up front and
        restored at nanosecond precision afterwards. mtime is load-bearing in
        this archive: it is the authoritative capture time for videos.

        preserve_mtime is off only for scratch files that a downstream tool
        must notice have changed.
        """
        if not assignments:
            return True
        if dry_run:
            for item in assignments:
                LOG.info("    [dry-run] %s %s", target.name, item)
            return True

        times = None
        if preserve_mtime and target.exists():
            st = target.stat()
            times = (st.st_atime_ns, st.st_mtime_ns)

        args = ["-P", "-overwrite_original", "-m"]
        if numeric:
            args.append("-n")
        proc = self.run([*args, *assignments, str(target)])
        if proc.returncode != 0:
            LOG.error(
                "exiftool write failed for %s: %s", target, proc.stderr.strip()
            )
            return False

        if times is not None and target.exists():
            os.utime(target, ns=times)
        return True
